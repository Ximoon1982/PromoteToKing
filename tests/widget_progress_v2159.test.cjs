"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const src=fs.readFileSync(path.join(__dirname,"../assets/js/widgets/p2k-progress-chart-v2159.js"),"utf8");
const window={};
vm.runInNewContext(src,{window,Intl,Date,Number,Math,String,Array,Error});
const {render,normalize,slopeOf}=window.P2K_PROGRESS_CHART;
const point=(day,value)=>({date:new Date(Date.UTC(2026,9,1+day)).toISOString().slice(0,10),value});
const daily=Array.from({length:45},(_,i)=>point(i,390000+i*450));
const settings={lowerReferencePoints:"385000",lowerReferenceLabel:"#10",upperReferencePoints:"435000",upperReferenceLabel:"#9"};
const image="https://www.promotetoking.org/assets/images/p2k-logo.jpg";
const chart=render(daily,settings,image);
assert(chart.svg.includes('viewBox="0 0 256 256"'),"square chart must have a 1:1 coordinate system");
assert.equal((chart.svg.match(/stroke-width="1.25"/g)||[]).length,2,"both reference levels need horizontal marks");
assert(chart.svg.includes("#10")&&chart.svg.includes("#9"),"both customized reference labels shown");
assert(chart.svg.includes('p2k-logo.jpg')&&chart.svg.includes('width="256" height="256" opacity="1" preserveAspectRatio="xMidYMid meet"'),"Original P2K logo fills the card in full color");
assert(chart.svg.includes('clipPath id="p2kw-progress-card-clip"'),"Backdrop is clipped to a rounded card");
assert(chart.svg.includes('rx="14" fill="none" stroke="var(--border)"'),"Graph has a rounded frame and visible border");
assert(chart.svg.includes('stroke="var(--blue)" stroke-width="2.6" stroke-dasharray="5 4"'),"Projected line uses a distinct blue stroke");
assert(chart.svg.includes('stroke="var(--gold)" stroke-width="2.6"'),"Historical line retains its gold stroke");
const targetPaths=[...chart.svg.matchAll(/<path d="M42 ([\d.]+)H246" stroke="var\(--gold\)"/g)];
assert.equal(targetPaths.length,2,"Both target reference lines appear");
const projectedPath=[...chart.svg.matchAll(/<path d="(M[\d. ]+L246\.0 [\d.]+)" stroke="var\(--blue\)"/g)][0];
assert(projectedPath,"Forecast reaches the chart right boundary");
const projectedEndY=Number(projectedPath[1].match(/L246\.0 ([\d.]+)/)[1]);
assert(projectedEndY<Number(targetPaths[1][1]),"Forecast end must plot slightly higher than upper target");
assert(chart.svg.includes('stroke-dasharray="5 4"'),"positive trend must show extrapolation");
assert(chart.message.includes("estimated")&&chart.forecast,"forecast ETA and date");
const farGoal=render(daily,{...settings,upperReferencePoints:"600000"},image);
assert(farGoal.forecast,"Long-term, positive target should retain an ETA");
assert(farGoal.svg.includes('stroke="var(--blue)"'),"Projection is drawn until slightly past a target more than 90 days away");
const farLines=[...farGoal.svg.matchAll(/<path d="M42 ([\d.]+)H246" stroke="var\(--gold\)"/g)];
const farProject=[...farGoal.svg.matchAll(/<path d="(M[\d. ]+L246\.0 [\d.]+)" stroke="var\(--blue\)"/g)][0];
assert(farProject&&Number(farProject[1].match(/L246\.0 ([\d.]+)/)[1])<Number(farLines[1][1]),"Long-term projection ends above its target");
assert(!chart.svg.includes('drop-line'),"no vertical drop line");
const capped=render(daily,{...settings,upperReferencePoints:"405000"},image);
assert(capped.message.includes("reached"),"achieved goal should not get a future ETA");
assert.equal(capped.forecast,null);
const stagnant=Array.from({length:35},(_,i)=>point(i,420000-i*10));
const flat=render(stagnant,settings,image);
assert.equal(flat.forecast,null,"negative trend must not fabricate an ETA");
assert(!flat.svg.includes('stroke-dasharray="5 4"'));
assert(!flat.svg.includes('stroke="var(--blue)"'),"No projection line if recent growth is not positive");
const none=render(daily,{},image);
assert.equal(none.forecast,null,"no configured upper reference means no forecast target");
assert(normalize([point(4,42),point(2,40),point(4,43)]).map(x=>x.value).join(",")==="40,43","chronological deduplication");
assert(slopeOf(daily.map((p,i)=>({day:100+i,value:i})))>0);
const css=fs.readFileSync(path.join(__dirname,"../assets/css/widgets/p2k-embed-v2153.css"),"utf8");
assert(css.includes(".p2kw-progress-chart{")&&css.includes("border-radius:14px")&&css.includes("box-shadow:0 5px 16px"),"Card styling and rounded corners");
const embed=fs.readFileSync(path.join(__dirname,"../server/widgets/public/embed.php"),"utf8");
assert(embed.includes("p2k-progress-chart-v2159.js?v=p2k-2159-progress-card-1"),"Updated chart script cache is invalidated");
assert(embed.includes("p2k-embed-v2153.css?v=p2k-2159-progress-card-1"),"Updated card style cache is invalidated");
console.log("PASS Club Progress full-color logo, rounded card, distinct projection, adaptive horizon and no fabricated ETA");
